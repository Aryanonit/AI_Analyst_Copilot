# --- Load and Prepare Your Custom Dataset ---
print("--- Loading and Preparing Dataset ---")
file_path = '/content/drive/MyDrive/Analyst/data/analyst_dataset.jsonl' # Make sure this path is correct
df = pd.read_json(path_or_buf=file_path, lines=True)

df['answer'] = df['answer'].astype(str)
hg_dataset = Dataset.from_pandas(df)

def format_prompt(example):
    return {"text": f"<start_of_turn>user\n{example['instruction']}\n\n{example['context']}<end_of_turn>\n<start_of_turn>model\n{example['answer']}<end_of_turn>"}

formatted_dataset = hg_dataset.map(format_prompt)
print(f"--- Dataset with {len(formatted_dataset)} lessons is Ready ---")

# --- Configure QLoRA and Load the Base Model ---
print("--- Configuring QLoRA and Loading Model ---")
bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_quant_type="nf4",
    bnb_4bit_compute_dtype=torch.bfloat16
)

model_id = "google/gemma-2b-it"

tokenizer = AutoTokenizer.from_pretrained(model_id, trust_remote_code=True)
if tokenizer.pad_token is None:
    tokenizer.pad_token = tokenizer.eos_token

model = AutoModelForCausalLM.from_pretrained(
    model_id,
    quantization_config=bnb_config,
    device_map="auto",
    trust_remote_code=True
)

lora_config = LoraConfig(
    r=16,
    lora_alpha=32,
    lora_dropout=0.05,
    bias="none",
    task_type="CAUSAL_LM",
    target_modules=["q_proj", "k_proj", "v_proj", "o_proj"]
)
print("--- Model and LoRA Config are Ready ---")

# --- Set up Training and Run the Fine-Tuning Process ---
output_dir = "/content/drive/MyDrive/Analyst/analyst_copilot_final_model" # Saving our final version

training_args = TrainingArguments(
    output_dir=output_dir,
    per_device_train_batch_size=1,
    gradient_accumulation_steps=8,
    learning_rate=2e-4,
    num_train_epochs=10,
    logging_steps=20,
    save_strategy="epoch",
    report_to="none",
)

trainer = SFTTrainer(
    model=model,
    train_dataset=formatted_dataset,
    peft_config=lora_config,
    args=training_args,
)

print("--- Starting the Fine-Tuning Process ---")
# This will take a significant amount of time as the dataset is now very large
trainer.train()

# --- Save the Final Trained Adapter ---
final_adapter_path = f"{output_dir}/final_adapter"
trainer.save_model(final_adapter_path)
print(f"--- SUCCESS! Phase 2 is complete. Your final model adapter is saved to: {final_adapter_path} ---")