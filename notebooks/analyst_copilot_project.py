# --- Step 3.2: Load and Prepare Your Custom Dataset ---
print("--- Loading and Preparing Dataset ---")
# IMPORTANT: Make sure this path is correct for your Google Drive!
file_path = '/content/drive/MyDrive/Analyst/data/analyst_dataset.jsonl'
df = pd.read_json(path_or_buf=file_path, lines=True)
hg_dataset = Dataset.from_pandas(df)

# This function creates the specific prompt format the Gemma model expects
def format_prompt(example):
    return {"text": f"<start_of_turn>user\n{example['instruction']}\n\n{example['context']}<end_of_turn>\n<start_of_turn>model\n{example['answer']}<end_of_turn>"}

formatted_dataset = hg_dataset.map(format_prompt)
final_dataset = formatted_dataset.train_test_split(test_size=0.1)
print("--- Dataset is Ready ---")

# --- Step 3.3: Configure QLoRA and Load the Base Model ---
print("--- Configuring QLoRA and Loading Model ---")
# This is the QLoRA configuration that shrinks the model to 4-bits
bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_quant_type="nf4",
    bnb_4bit_compute_dtype=torch.bfloat16
)

# This is the specific open-source model we are specializing
model_id = "google/gemma-2b-it"

tokenizer = AutoTokenizer.from_pretrained(model_id, trust_remote_code=True)
if tokenizer.pad_token is None:
    # Many models don't have a padding token, so we have to add one
    tokenizer.pad_token = tokenizer.eos_token

model = AutoModelForCausalLM.from_pretrained(
    model_id,
    quantization_config=bnb_config,
    device_map="auto", # This automatically uses our Colab GPU
    trust_remote_code=True
)

# This is the configuration for our LoRA "sticky notes"
lora_config = LoraConfig(
    r=8,
    lora_alpha=32,
    lora_dropout=0.05,
    bias="none",
    task_type="CAUSAL_LM",
    target_modules=["q_proj", "k_proj", "v_proj", "o_proj"]
)
print("--- Model and LoRA Config are Ready ---")

# --- Step 3.4: Set up Training and Run the Fine-Tuning Process ---
# Define where to save our final model adapter
output_dir = "/content/drive/MyDrive/Analyst/analyst_copilot_v1"

# Define the training arguments (without max_seq_length)
training_args = TrainingArguments(
    output_dir=output_dir,
    per_device_train_batch_size=1,
    gradient_accumulation_steps=8,
    learning_rate=2e-4,
    num_train_epochs=1,
    logging_steps=5,
    save_strategy="epoch",
    report_to="none",
)
# Create the Trainer object
trainer = SFTTrainer(
    model=model,
    train_dataset=final_dataset['train'],
    peft_config=lora_config,
    args=training_args,
    # Both dataset_text_field and max_seq_length have now been removed
)
print("--- Starting the Fine-Tuning Process ---")
# This one command starts the entire training job!
trainer.train()

# --- Step 3.5: Save the Final Trained Adapter ---
final_adapter_path = f"{output_dir}/final_adapter"
trainer.save_model(final_adapter_path)
print(f"--- SUCCESS! Phase 2 is complete. Your fine-tuned model adapter is saved to: {final_adapter_path} ---")



