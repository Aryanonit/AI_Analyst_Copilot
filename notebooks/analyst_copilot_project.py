# --- Step 2: Load the Base Model and Tokenizer ---
print("--- Loading Base Model (Gemma-2B-IT) ---")
model_id = "google/gemma-2b-it"

# Use the same 4-bit configuration as during training
bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_quant_type="nf4",
    bnb_4bit_compute_dtype=torch.bfloat16
)

tokenizer = AutoTokenizer.from_pretrained(model_id, trust_remote_code=True)
base_model = AutoModelForCausalLM.from_pretrained(
    model_id,
    quantization_config=bnb_config,
    device_map="auto",
    trust_remote_code=True
)
print("--- Base Model Loaded ---")


# --- Step 3: Load Your Fine-Tuned Adapter ---
# This is where we load the "brain" you trained
print("--- Loading Your Fine-Tuned Adapter ---")
adapter_path = "/content/drive/MyDrive/Analyst/analyst_copilot_v1/final_adapter"
model = PeftModel.from_pretrained(base_model, adapter_path)
print("--- Adapter Loaded Successfully ---")


# --- Step 4: Prepare and Run Your Test Prompt ---
print("\n--- Asking our new AI its first question... ---")
# Let's test it on the competitor identification task
test_instruction = "Based on the provided text describing the company's competitive landscape, list its main competitors."
# This is the same context we used in our dataset
test_context = """
Competitors to Office include software and global application vendors, such as Apple, Cisco Systems, Google, Meta, Proofpoint, Slack, Symantec, Zoom... Dynamics competes with cloud-based and on-premises business solution providers such as Oracle, Salesforce, SAP, Service Now, UI Path, and WorkDay. Azure faces diverse competition from companies such as Amazon, Broadcom, Google, IBM, Oracle, and open source offerings...
"""

# Format the prompt using the exact same template we used for training
prompt = f"<start_of_turn>user\n{test_instruction}\n\n{test_context}<end_of_turn>\n<start_of_turn>model\n"

# --- Step 5: Generate and Print the Answer ---
inputs = tokenizer(prompt, return_tensors="pt").to("cuda")

with torch.no_grad():
    outputs = model.generate(**inputs, max_new_tokens=256, temperature=0.1)

# Decode the output
response_text = tokenizer.decode(outputs[0], skip_special_tokens=True)

# The model will output the full prompt, so we split to get just the answer
# This finds where the model's answer starts and prints only that part
answer_start = response_text.find("<start_of_turn>model\n")
final_answer = response_text[answer_start + len("<start_of_turn>model\n"):]


print("\n✅ AI Co-pilot's Answer:")
print(final_answer)

